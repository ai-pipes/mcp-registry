package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// licenceFile matches the files at a package's root that carry its licence or notices.
var licenceFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|patents|unlicense)([._-].*)?$`)

const (
	rule  = "================================================================================\n"
	thin  = "--------------------------------------------------------------------------------\n"
	pins  = "internal/modules/search/infra/onnx/native/pins.env"
	gen   = "(generated by `go run ./tools/notices %s`; do not edit by hand)\n"
	noLic = "(no licence file in the package)\n"
)

// licenceFiles returns the names of the licence files directly in dir, sorted.
func licenceFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range entries {
		if !e.IsDir() && licenceFile.MatchString(e.Name()) {
			out = append(out, e.Name())
		}
	}
	slices.Sort(out)
	return out, nil
}

// texts remembers the licence texts already written to one output, so that a text shipped by many
// packages (the Apache License 2.0, say) is written once and referred to afterwards.
type texts map[string]string

// section writes one component: a heading, then each named file of dir (relative names, so a file
// in a subdirectory may be named) verbatim, line endings normalised; a text identical to one
// written earlier in the same output is replaced by a reference to it.
func section(b *bytes.Buffer, seen texts, heading string, dir string, files []string) error {
	b.WriteString(rule)
	b.WriteString(heading + "\n")
	if len(files) == 0 {
		b.WriteString(thin)
		b.WriteString(noLic)
	}
	for _, f := range files {
		text, err := os.ReadFile(filepath.Join(dir, f)) //nolint:gosec // G304: a licence file of a package the tool lists
		if err != nil {
			return err
		}
		b.WriteString(thin)
		norm := normalise(string(text))
		name := filepath.ToSlash(f)
		if first, ok := seen[norm]; ok {
			b.WriteString(name + ": the same text as " + first + " above\n")
			continue
		}
		seen[norm] = name + " of " + heading
		b.WriteString(name + ":\n\n")
		b.WriteString(norm)
	}
	return nil
}

// normalise makes the text byte-stable across checkouts: LF line endings, no trailing blanks at the
// end of a line, exactly one newline at the end.
func normalise(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		lines[i] = strings.TrimRight(l, " \t\r")
	}
	return strings.TrimRight(strings.Join(lines, "\n"), "\n") + "\n"
}

// readPins parses pins.env (plain NAME=value lines).
func readPins(root string) (map[string]string, error) {
	data, err := os.ReadFile(filepath.Join(root, pins)) //nolint:gosec // G304: a fixed path in the repository
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if k, v, ok := strings.Cut(line, "="); ok {
			out[k] = v
		}
	}
	return out, nil
}

// versionIn is the first MAJOR.MINOR.PATCH in s ("" if none).
func versionIn(s string) string {
	return regexp.MustCompile(`\d+\.\d+\.\d+`).FindString(s)
}

func writeFile(root, rel string, data []byte) error {
	path := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil { //nolint:gosec // G301: a directory of the repository
		return err
	}
	if err := os.WriteFile(path, data, 0o644); err != nil { //nolint:gosec // G306: a committed text file
		return err
	}
	fmt.Println("wrote", rel)
	return nil
}
